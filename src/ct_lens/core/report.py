"""Assemble a Markdown report from the analysis and findings (README §3.5).

The report is designed to seed the companion write-up ("The certificate
landscape of .lk, 2026"): it leads with the ecosystem "report card", embeds the
charts when they were rendered, and lists security findings in **anonymised
aggregate** by default, in line with the project's disclosure rules (§5/§6).
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path

from ct_lens.core.analysis import EcosystemAnalysis
from ct_lens.core.findings import Finding

#: Type of the ``add`` line-appender passed to the section helpers.
_Writer = Callable[[str], None]

#: Friendly captions for each chart file (by filename stem).
_CHART_CAPTIONS: dict[str, str] = {
    "ca_shares": "Certificate Authority market share",
    "lifetimes": "Certificate lifetime distribution",
    "issuance_over_time": "Issuance over time",
}


def generate_markdown(
    analysis: EcosystemAnalysis,
    findings: list[Finding],
    *,
    chart_files: list[Path] | None = None,
    generated_at: datetime | None = None,
    anonymized: bool = True,
) -> str:
    """Render the full report as a Markdown string."""
    generated_at = generated_at or datetime.now(timezone.utc)
    lines: list[str] = []
    add = lines.append

    add(f"# Certificate landscape — `{analysis.pattern}`")
    add("")
    add(
        f"*Generated by [ct-lens](https://github.com/your-org/ct-lens) on "
        f"{generated_at.strftime('%Y-%m-%d %H:%M UTC')} from public Certificate "
        f"Transparency logs. No target server was contacted.*"
    )
    add("")

    _overview(add, analysis)
    _ca_section(add, analysis)
    _lifetime_section(add, analysis)
    _issuance_section(add, analysis)
    _crypto_section(add, analysis)
    _charts_section(add, chart_files or [])
    _findings_section(add, findings, anonymized=anonymized)
    _methodology(add)

    return "\n".join(lines) + "\n"


def _overview(add: _Writer, a: EcosystemAnalysis) -> None:
    add("## Overview")
    add("")
    add(f"- **Certificates analysed:** {a.total_certificates:,}")
    add(f"- **Unique domains:** {a.unique_domains:,}")
    add(f"- **Wildcard certificates:** {a.wildcard_count:,}")
    if a.ca_shares:
        add(f"- **Largest CA share:** {a.ca_concentration_top1:.1%} ({a.ca_shares[0].issuer})")
        add(f"- **Top-3 CA concentration:** {a.ca_concentration_top3:.1%}")
    add("")


def _ca_section(add: _Writer, a: EcosystemAnalysis) -> None:
    if not a.ca_shares:
        return
    add("## Who issues HTTPS certificates?")
    add("")
    add("| Certificate Authority | Certificates | Share |")
    add("| --- | ---: | ---: |")
    for item in a.ca_shares[:15]:
        add(f"| {item.issuer} | {item.count:,} | {item.share:.1%} |")
    add("")


def _lifetime_section(add: _Writer, a: EcosystemAnalysis) -> None:
    life = a.lifetimes
    if not life.count:
        return
    add("## Certificate hygiene — lifetimes")
    add("")
    add(
        f"Across {life.count:,} certificates with usable dates: "
        f"min **{life.min_days}**, median **{life.median_days}**, "
        f"mean **{life.mean_days}**, max **{life.max_days}** days."
    )
    add("")
    add("| Lifetime | Certificates |")
    add("| --- | ---: |")
    for label, count in life.buckets:
        add(f"| {label} | {count:,} |")
    add("")


def _issuance_section(add: _Writer, a: EcosystemAnalysis) -> None:
    if not a.issuance_by_month:
        return
    add("## Issuance over time")
    add("")
    add("| Month | Certificates |")
    add("| --- | ---: |")
    for item in a.issuance_by_month:
        add(f"| {item.period} | {item.count:,} |")
    add("")


def _crypto_section(add: _Writer, a: EcosystemAnalysis) -> None:
    if not a.key_types and not a.signature_algorithms:
        return
    add("## Cryptographic hygiene")
    add("")
    if a.key_types:
        add("**Key types:** " + ", ".join(f"{name} ({count:,})" for name, count in a.key_types))
        add("")
    if a.signature_algorithms:
        add(
            "**Signature algorithms:** "
            + ", ".join(f"{name} ({count:,})" for name, count in a.signature_algorithms)
        )
        add("")


def _charts_section(add: _Writer, chart_files: list[Path]) -> None:
    if not chart_files:
        return
    add("## Charts")
    add("")
    for path in chart_files:
        caption = _CHART_CAPTIONS.get(path.stem, path.stem.replace("_", " ").title())
        add(f"![{caption}]({path.name})")
        add("")


def _findings_section(add: _Writer, findings: list[Finding], *, anonymized: bool) -> None:
    add("## Security findings")
    add("")
    note = "anonymised" if anonymized else "**not anonymised — handle privately**"
    add(f"*Findings below are {note}.*")
    add("")
    if not findings:
        add("No findings.")
        add("")
        return

    by_category: Counter[str] = Counter(f.category for f in findings)
    add("| Category | Count |")
    add("| --- | ---: |")
    for category, count in by_category.most_common():
        add(f"| {category} | {count:,} |")
    add("")

    add("| Severity | Category | Domain | Summary |")
    add("| --- | --- | --- | --- |")
    for f in findings:
        add(f"| {f.severity} | {f.category} | `{f.domain}` | {f.summary} |")
    add("")


def _methodology(add: _Writer) -> None:
    add("## Methodology & safety")
    add("")
    add(
        "- **Source:** public Certificate Transparency logs via crt.sh. "
        "Every HTTPS certificate must be logged, so CT is a near-complete public record."
    )
    add(
        "- **No target contact:** ct-lens never connects to, scans, or probes any "
        "server. All findings are derived from public log metadata alone."
    )
    add(
        "- **De-duplication:** pre-certificate / final-certificate pairs are collapsed "
        "so counts and CA shares are not inflated."
    )
    add(
        "- **Disclosure:** sensitive individual findings should be reported privately "
        "to the affected organisation and to Sri Lanka CERT|CC / TechCERT before any "
        "non-anonymised publication."
    )
    add("")


def write_report(markdown: str, path: Path) -> Path:
    """Write the Markdown report to ``path`` (creating parents). Returns the path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown, encoding="utf-8")
    return path
